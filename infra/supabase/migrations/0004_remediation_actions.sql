-- Action immutability: once an action is approved, its core definition
-- (action_type, parameters, rollback_definition, closes_finding_ids) is
-- locked. The only fields that can change are the status fields.
create or replace function public.actions_approved_immutable()
returns trigger language plpgsql as $$
begin
  if old.approval_status in ('approved', 'executing', 'succeeded') then
    if new.action_type is distinct from old.action_type then
      raise exception 'action_type is immutable once approved';
    end if;
    if new.parameters is distinct from old.parameters then
      raise exception 'parameters are immutable once approved';
    end if;
    if new.rollback_definition is distinct from old.rollback_definition then
      raise exception 'rollback_definition is immutable once approved';
    end if;
    if new.closes_finding_ids is distinct from old.closes_finding_ids then
      raise exception 'closes_finding_ids is immutable once approved';
    end if;
  end if;
  return new;
end;
$$;

create trigger trg_actions_approved_immutable
  before update on public.remediation_actions
  for each row execute function public.actions_approved_immutable();
